def fill(color):
    return PatternFill("solid", fgColor=color)


def thin_border(color=LINE):
    side = Side(style="thin", color=color)
    return Border(left=side, right=side, top=side, bottom=side)


def setup_sheet(ws, title, subtitle, widths, tab_color=GOLD, freeze="A4"):
    ws.sheet_view.showGridLines = False
    ws.sheet_view.zoomScale = 88
    ws.sheet_properties.tabColor = tab_color
    for idx, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width
    last_col = get_column_letter(len(widths))
    ws.merge_cells(f"A1:{last_col}1")
    c = ws["A1"]
    c.value = title
    c.font = Font(name=TITLE_FONT, size=20, bold=True, color=WHITE)
    c.fill = fill(INK)
    c.alignment = Alignment(vertical="center", horizontal="left", indent=1)
    ws.row_dimensions[1].height = 40
    ws.merge_cells(f"A2:{last_col}2")
    c = ws["A2"]
    c.value = subtitle
    c.font = Font(name=FONT, size=9.5, color=GREY)
    c.fill = fill(CREAM)
    c.alignment = Alignment(vertical="center", horizontal="left", indent=1, wrap_text=True)
    ws.row_dimensions[2].height = 28
    if freeze:
        ws.freeze_panes = freeze
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.sheet_properties.pageSetUpPr.fitToPage = True


def section(ws, row, title, ncols):
    last_col = get_column_letter(ncols)
    ws.merge_cells(f"A{row}:{last_col}{row}")
    c = ws.cell(row=row, column=1, value=title)
    c.font = Font(name=FONT, size=10.5, bold=True, color=INK)
    c.fill = fill(GOLD_LIGHT)
    c.alignment = Alignment(vertical="center", horizontal="left", indent=1)
    ws.row_dimensions[row].height = 24
    return row + 1


def table(ws, row, headers, rows, widths=None, row_height=34, header_height=28):
    for col, header in enumerate(headers, start=1):
        c = ws.cell(row=row, column=col, value=header)
        c.font = Font(name=FONT, size=9, bold=True, color=WHITE)
        c.fill = fill(INK_SOFT)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = thin_border(INK_SOFT)
    ws.row_dimensions[row].height = header_height
    if widths:
        for col, width in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(col)].width = width
    for i, data_row in enumerate(rows, start=1):
        r = row + i
        for col, value in enumerate(data_row, start=1):
            c = ws.cell(row=r, column=col, value=value)
            c.font = Font(name=FONT, size=9, color=INK)
            c.fill = fill(PAPER_ALT if i % 2 else WHITE)
            c.alignment = Alignment(vertical="top", horizontal="left", wrap_text=True)
            c.border = thin_border()
        ws.row_dimensions[r].height = row_height
    return row + len(rows) + 2


def note(ws, row, text, ncols):
    last_col = get_column_letter(ncols)
    ws.merge_cells(f"A{row}:{last_col}{row}")
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=9, italic=True, color=GREY)
    c.fill = fill(PAPER)
    c.alignment = Alignment(vertical="top", horizontal="left", wrap_text=True, indent=1)
    ws.row_dimensions[row].height = 30
    return row + 2


